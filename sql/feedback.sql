-- =========================================================
--  个人主页 V3 · feedback 反馈表 建表 + 权限脚本
--  用法：Supabase → SQL Editor → New query → 粘贴 → Run
-- =========================================================

-- 1) 建表：每条访客反馈 = 表里的一行
create table if not exists public.feedback (
  id          bigint generated by default as identity primary key,  -- 唯一编号，自动生成
  name        text,                                    -- 昵称（可选）
  relation    text,                                    -- 与主页主人的关系
  device      text,                                    -- 本条反馈针对的设备
  message     text not null,                           -- 反馈内容（必填）
  version     text,                                    -- 提交时自动附带的网站版本
  created_at  timestamptz not null default current_timestamp  -- 提交时间，默认当前时间
);

-- 2) 开启行级安全（RLS）：默认拒绝一切，必须显式写策略
alter table public.feedback enable row level security;

-- 3) 策略：允许公开访客（anon）与已登录用户「提交新反馈」
--    注意：这里只给 INSERT，读/改/删一律拒绝 —— 安全在数据库层，不靠页面隐藏按钮。
drop policy if exists "feedback_anon_insert" on public.feedback;
create policy "feedback_anon_insert"
  on public.feedback
  for insert
  to anon, authenticated
  with check (true);

-- 说明：
--   · 你本人在 Supabase Table Editor 用管理员身份查看反馈，不受 RLS 限制。
--   · 访客不会被授予 SELECT 权限，因此读不到别人的反馈。
--   · 红线：不要为了消除报错而关闭 RLS 或放开全部权限。
